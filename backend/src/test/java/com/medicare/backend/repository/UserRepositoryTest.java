package com.medicare.backend.repository;

import com.medicare.backend.entity.User;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;

import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
class UserRepositoryTest {

    @Autowired
    private UserRepository userRepository;

    @Test
    void testCreateFindAndDeleteUser() {
        String testEmail = "patient_" + System.currentTimeMillis() + "@test.com";
        User user = new User("Priya Sharma", testEmail, "testPassword123", "PATIENT");

        // 1. Save user to the database
        User savedUser = userRepository.save(user);
        assertNotNull(savedUser.getId(), "User ID should be generated by MySQL");

        // 2. Find user by unique email
        Optional<User> foundUser = userRepository.findByEmail(testEmail);
        assertTrue(foundUser.isPresent(), "User should be found in the database");
        assertEquals("Priya Sharma", foundUser.get().getFullName());
        assertEquals("PATIENT", foundUser.get().getRole());

        // 3. Check if email exists
        assertTrue(userRepository.existsByEmail(testEmail));

        // 4. Clean up test data so database remains clean
        userRepository.delete(savedUser);
        assertFalse(userRepository.existsByEmail(testEmail));
    }
}
